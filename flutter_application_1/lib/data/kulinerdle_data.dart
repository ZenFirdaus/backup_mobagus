/// Mendapatkan kata target harian berdasarkan tanggal
KulinerdleWord getDailyKulinerdleWord([DateTime? date]) {
  final d = date ?? DateTime.now();
  final seed = d.year * 10000 + d.month * 100 + d.day;
  final idx = seed % kKulinerdleTargetWords.length;
  return kKulinerdleTargetWords[idx];
}

/// Mendapatkan kata acak untuk mode latihan / ronde bebas
/// Menerima parameter [exclude] berupa int (index) atau String (kata), serta [excludeWords] daftar kata yang ingin dihindari agar tidak berulang.
KulinerdleWord getRandomKulinerdleWord([
  dynamic exclude,
  Iterable<String>? excludeWords,
]) {
  int? excludeIndex;
  String? excludeWord;
  if (exclude is int) {
    excludeIndex = exclude;
  } else if (exclude is String) {
    excludeWord = exclude;
  }

  final random = Random();
  final candidates = kKulinerdleTargetWords.where((w) {
    if (excludeWord != null &&
        w.word.toUpperCase() == excludeWord.toUpperCase()) {
      return false;
    }
    if (excludeWords != null &&
        excludeWords.any((ex) => ex.toUpperCase() == w.word.toUpperCase())) {
      return false;
    }
    return true;
  }).toList();

  final pool = candidates.isNotEmpty ? candidates : kKulinerdleTargetWords;
  int idx = random.nextInt(pool.length);
  if (excludeIndex != null && pool.length > 1 && idx == excludeIndex) {
    idx = (idx + 1) % pool.length;
  }
  return pool[idx];
}
